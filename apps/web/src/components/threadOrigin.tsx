export interface ThreadOrigin {
  readonly kind: string;
  readonly text: string;
}

export function parseThreadOrigin(title: string): ThreadOrigin | null {
  const match = THREAD_ORIGIN_PATTERN.exec(title);
  return match ? { kind: match[1] ?? "", text: title.slice(match[0].length) } : null;
}

export function plainThreadTitle(title: string): string {
  return parseThreadOrigin(title)?.text ?? title;
}

function OriginIcon({ kind }: { readonly kind: string }): ReactNode {
  const label = ORIGIN_LABELS[kind] ?? kind;
  const branded = BRAND_ORIGINS[kind];
  const className = "mr-1.5 inline size-3.5 shrink-0 align-[-0.125rem]";

  if (branded) {
    return (
      <svg
        aria-label={`from ${label}`}
        className={className}
        fill={branded.color}
        role="img"
        viewBox="0 0 24 24"
      >
        <path d={branded.path} />
      </svg>
    );
  }
  const GenericIcon = kind === "mail" ? Mail : kind === "dashboard" ? Monitor : SquareTerminal;
  if (kind === "mail" || kind === "dashboard" || kind === "cli") {
    return <GenericIcon aria-label={`from ${label}`} className={className} role="img" />;
  }
  return (
    <span
      aria-label={`from ${label}`}
      className="mr-1.5 inline-block rounded border border-current/60 px-1 text-[10px] leading-4 opacity-70"
      role="img"
    >
      {kind}
    </span>
  );
}

export function ThreadOriginTitle({ title }: { readonly title: string }) {
  const origin = parseThreadOrigin(title);
  if (!origin) return title;
  return (
    <>
      <OriginIcon kind={origin.kind} />
      {origin.text}
    </>
  );
}
